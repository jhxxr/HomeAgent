const exec = promisify(execFile);
const payload = (result: ToolResult) => {
  assert.ok(!result.isError, result.content[0]!.text);
  return JSON.parse(result.content[0]!.text);
};

test('2026 MCP coding workflow: diagnose failing Node tests, batch read, patch, retest, isolated commit, then resume after relay restart', async t => {
  const f = await fixture(), port = await freePort(), base = `http://127.0.0.1:${port}`;
  const git = (...args: string[]) => exec('git', ['-C', f.root, ...args]);
  await writeFile(path.join(f.root, 'calc.cjs'), 'module.exports = (a, b) => a - b;\n');
  await writeFile(path.join(f.root, 'calc.test.cjs'), 'const test=require("node:test");const assert=require("node:assert/strict");test("adds",()=>assert.equal(require("./calc.cjs")(2,3),5));\n');
  await writeFile(path.join(f.root, 'package.json'), JSON.stringify({ name: 'coding-fixture', scripts: { test: 'node --test calc.test.cjs' } }));
  await writeFile(path.join(f.root, 'AGENTS.md'), 'Run the project test command before completing a change.\n');
  await writeFile(path.join(f.root, 'user.txt'), 'initial user file');
  await writeFile(path.join(f.root, '.gitignore'), 'ignored.txt\n');
  await git('init'); await git('config', 'user.name', 'Workflow Test'); await git('config', 'user.email', 'workflow@localhost');
  await git('add', '.'); await git('commit', '-m', 'initial');
  await writeFile(path.join(f.root, 'user.txt'), 'user staged change'); await git('add', 'user.txt');
  await writeFile(path.join(f.root, 'ignored.txt'), 'a - b should not be found here');
  f.config.server = base;
  f.config.projects[0]!.commandAliases = { tests: { executable: process.execPath, args: ['--test', 'calc.test.cjs'] } };
  const config = { host: '127.0.0.1', port, publicUrl: base, db: path.join(f.directory, 'server.sqlite'), password: 'workflow-test-password', sessionSecret: 's'.repeat(64), trustProxyHops: 0, retentionDays: 90 };
  let relay = createHomeServer(config); await relay.listen();
  const deviceId = randomUUID(), deviceToken = secret();
  relay.store.put('devices', deviceId, { id: deviceId, name: 'workflow-device', tokenHash: hash(deviceToken), revoked: false, paused: false, projects: [], platform: '', lastSeen: 0, created: Date.now() });
  const token = relay.store.mintToken({ id: 'workflow-client', clientId: 'workflow', family: randomUUID(), kind: 'pat', scopes: ['read', 'write', 'execute', 'git'], devices: [deviceId], projects: ['workspace'], expires: Date.now() + 120000 });
  const agent = new Agent(f.config, { server: base, deviceId, token: deviceToken }, () => {}); agent.start();
  const clients: Client[] = [];
  t.after(async () => { for (const client of clients) await client.close(); await agent.close(); await relay.close(); await f.cleanup(); });
  const connect = async () => {
    const client = new Client({ name: 'coding-workflow', version: '1' }, { versionNegotiation: { mode: { pin: '2026-07-28' } } });
    clients.push(client);
    await client.connect(new StreamableHTTPClientTransport(new URL(base + '/mcp'), { requestInit: { headers: { Authorization: `Bearer ${token}` } } }));
    return client;
  };
  await waitFor(() => relay.hub.devices().some(device => device.online));
  assert.deepEqual((relay.hub.devices()[0]!.projects[0] as unknown as { commandAliasNames: string[] }).commandAliasNames, ['tests']);
  let client = await connect(), calls = 0;
  const call = async (name: string, args: object = {}) => { calls++; return payload(await client.callTool({ name, arguments: { deviceId, projectId: 'workspace', ...args } }) as ToolResult); };
  const context = await call('get_project_context');
  assert.equal(context.aliases[0].name, 'tests'); assert.ok(context.instructions[0].text.includes('Run the project test'));
  const failed = await call('run_command', { executable: 'tests', waitMs: 10000, idempotencyKey: 'baseline-test' });
  assert.equal(failed.state, 'failed'); assert.equal(failed.exitCode, 1);
  const found = await call('search_files', { query: 'a - b', content: true, include: ['**/*.cjs'], contextLines: 1 });
  assert.equal(found.gitIgnoreApplied, true); assert.equal(found.matches.length, 1); assert.equal(found.matches[0].path, 'calc.cjs');
  const read = await call('read_files', { files: [{ path: 'calc.cjs' }, { path: 'calc.test.cjs' }] });
  const diff = '--- a/calc.cjs\n+++ b/calc.cjs\n@@ -1 +1 @@\n-module.exports = (a, b) => a - b;\n+module.exports = (a, b) => a + b;\n--- /dev/null\n+++ b/README.md\n@@ -0,0 +1 @@\n+Addition is verified by the project test.\n';
  await call('apply_unified_diff', { diff, expectedSha256: { 'calc.cjs': read.files[0].sha256, 'README.md': null } });
  const passed = await call('run_command', { executable: 'tests', waitMs: 10000, idempotencyKey: 'fixed-test' });
  assert.equal(passed.state, 'exited'); assert.equal(passed.exitCode, 0);
  const review = await client.callTool({ name: 'git_diff', arguments: { deviceId, projectId: 'workspace' } }) as ToolResult; calls++;
  assert.ok(review.content[0]!.text.includes('a + b'));
  const commit = await call('git_commit_paths', { files: [{ path: 'calc.cjs', expectedSha256: sha256('module.exports = (a, b) => a + b;\n') }, { path: 'README.md', expectedSha256: sha256('Addition is verified by the project test.\n') }], expectedHead: context.git.head, message: 'Fix addition and document test coverage' });
  assert.ok(commit.commit); assert.equal((await git('diff', '--cached', '--name-only')).stdout.trim(), 'user.txt');
  await call('save_project_note', { text: `Fixed addition; tests passed; commit ${commit.commit}. User's staged user.txt remains untouched.` });
  await client.close(); await relay.close();
  relay = createHomeServer(config); await relay.listen();
  await waitFor(() => relay.hub.devices().some(device => device.online));
  client = await connect();
  const resumed = await call('get_project_context');
  assert.ok(resumed.note.text.includes(commit.commit)); assert.ok(resumed.jobs.some((job: { id: string }) => job.id === passed.id));
  assert.equal((await git('diff', '--cached', '--name-only')).stdout.trim(), 'user.txt');
  assert.equal(calls, 10);
});

test('real Python unittest can be diagnosed, edited with hashes and rerun through the same Runner tools', async t => {
  const python = process.env.HOMEAGENT_TEST_PYTHON ?? (process.platform === 'win32' ? 'python' : 'python3');
  const probe = spawnSync(python, ['--version'], { windowsHide: true, encoding: 'utf8' });
  if (probe.status !== 0) { t.skip('Python is not installed; set HOMEAGENT_TEST_PYTHON to an available interpreter'); return; }
  const f = await fixture(); f.config.projects[0]!.commands.push(python);
  const tools = new Tools(f.config);
  const principal: Principal = { id: 'python-workflow', scopes: ['read', 'write', 'execute'], devices: null, projects: ['workspace'] };
  t.after(async () => { await tools.close(); await f.cleanup(); });
  const call = async (name: string, args: object) => payload(await tools.invoke(name, { projectId: 'workspace', ...args }, principal));
  await writeFile(path.join(f.root, 'calc.py'), 'def add(a, b):\n    return a - b\n');
  await writeFile(path.join(f.root, 'test_calc.py'), 'import unittest\nfrom calc import add\nclass CalcTests(unittest.TestCase):\n    def test_add(self):\n        self.assertEqual(add(2, 3), 5)\n');
  const failed = await call('run_command', { executable: python, args: ['-B', '-m', 'unittest', '-v'], waitMs: 10000 });
  assert.equal(failed.state, 'failed'); assert.ok(failed.output.includes('FAIL'));
  const read = await call('read_files', { files: [{ path: 'calc.py', startLine: 1, endLine: 2 }] });
  await call('edit_files', { changes: [{ operation: 'edit', path: 'calc.py', expectedSha256: read.files[0].sha256, edits: [{ oldText: 'a - b', newText: 'a + b' }] }] });
  const passed = await call('run_command', { executable: python, args: ['-B', '-m', 'unittest', '-v'], waitMs: 10000 });
  assert.equal(passed.state, 'exited', passed.output); assert.ok(passed.output.includes('OK'));
  assert.ok((await readFile(path.join(f.root, 'calc.py'), 'utf8')).includes('a + b'));
});
