test('end to end: pairing, authenticated MCP, multi-device routing, grants, pause, audit and revocation', async t => {
  const f = await fixture(), port = await freePort(), base = `http://127.0.0.1:${port}`;
  const relay = createHomeServer({ host: '127.0.0.1', port, publicUrl: base, db: path.join(f.directory, 'server.sqlite'), password: 'test-password-strong-123', sessionSecret: 's'.repeat(64), trustProxyHops: 0, retentionDays: 90 });
  await relay.listen();
  const agents: Agent[] = [], clients: Client[] = [];
  t.after(async () => { for (const client of clients) await client.close(); for (const agent of agents) await agent.close(); await relay.close(); await f.cleanup(); });
  const post = (url: string, data: object, headers: Record<string, string> = {}) => fetch(base + url, { method: 'POST', headers: { 'content-type': 'application/json', ...headers }, body: JSON.stringify(data), redirect: 'manual' });
  assert.equal((await fetch(`${base}/mcp`)).status, 401);
  assert.equal((await fetch(`${base}/health`, { headers: { Origin: 'https://evil.example' } })).status, 403);
  assert.equal((await post('/login', { password: 'test-password-strong-123' }, { origin: 'https://evil.example' })).status, 403);
  const login = await post('/login', { password: 'test-password-strong-123' }, { origin: base });
  assert.equal(login.status, 302);
  assert.equal(login.headers.get('referrer-policy'), 'same-origin');
  const cookie = login.headers.getSetCookie()[0]!.split(';')[0]!;
  const state = await (await fetch(base + '/api/state', { headers: { cookie } })).json() as any;
  const admin = { cookie, 'x-csrf-token': state.csrf, origin: base };
  assert.equal((await post('/api/pair/approve', { code: '0000000000' }, { cookie })).status, 403);
  const start = await (await post('/pair/start', { name: 'test-device' })).json() as any;
  assert.equal((await post('/pair/claim', { id: start.id, pollToken: 'wrong' })).status, 401);
  assert.equal((await post('/pair/claim', { id: start.id, pollToken: start.pollToken })).status, 202);
  assert.equal((await post('/api/pair/approve', { code: start.code }, admin)).status, 200);
  assert.equal((await post('/api/pair/approve', { code: start.code }, admin)).status, 400);
  const credential = await (await post('/pair/claim', { id: start.id, pollToken: start.pollToken })).json() as any;
  assert.equal((await post('/pair/claim', { id: start.id, pollToken: start.pollToken })).status, 401);
  f.config.server = base;
  const agent = new Agent(f.config, { ...credential, server: base }, () => {}); agents.push(agent); agent.start();
  await waitFor(() => relay.hub.devices().some(device => device.online));
  const mint = async (scopes: string[], devices = [credential.deviceId], projects: string[] | null = null) => {
    const response = await post('/api/tokens', { name: 'test-client', scopes, devices, projects, expiresDays: 1 }, admin);
    assert.equal(response.status, 201); return response.json() as Promise<any>;
  };
  const makeClient = async (token: string) => {
    const client = new Client({ name: 'integration', version: '1.0' }); clients.push(client);
    await client.connect(new StreamableHTTPClientTransport(new URL(base + '/mcp'), { requestInit: { headers: { Authorization: `Bearer ${token}` } } }));
    return client;
  };
  const pat = await mint(['read', 'write', 'execute', 'git']), client = await makeClient(pat.token);
  const definitions = await client.listTools();
  assert.equal(definitions.tools.length, toolDefinitions.length + 1);
  const devices = await client.callTool({ name: 'list_devices', arguments: {} }) as any;
  assert.equal(JSON.parse(devices.content[0].text)[0].id, credential.deviceId);
  const write = await client.callTool({ name: 'write_file', arguments: { projectId: 'workspace', path: 'from-mcp.txt', content: 'private-content-marker' } }) as any;
  assert.ok(!write.isError);
  const read = await client.callTool({ name: 'read_file', arguments: { projectId: 'workspace', path: 'from-mcp.txt' } }) as any;
  assert.equal(JSON.parse(read.content[0].text).text, 'private-content-marker');
  const readOnly = await makeClient((await mint(['read'])).token);
  assert.equal((await readOnly.callTool({ name: 'write_file', arguments: { projectId: 'workspace', path: 'forbidden', content: 'x' } })).isError, true);
  const restricted = await makeClient((await mint(['read'], [credential.deviceId], ['other-project'])).token);
  assert.equal((await restricted.callTool({ name: 'read_file', arguments: { projectId: 'workspace', path: 'from-mcp.txt' } })).isError, true);
  // A second online authorized device makes omission of deviceId an explicit error.
  const second = randomUUID(), secondToken = 'x'.repeat(64);
  const { hash } = await import('../src/server/store.js');
  relay.store.put('devices', second, { id: second, name: 'second', tokenHash: hash(secondToken), revoked: false, paused: false, projects: [], platform: '', lastSeen: 0, created: Date.now() });
  const secondFixture = await fixture(); t.after(secondFixture.cleanup);
  secondFixture.config.server = base;
  const secondAgent = new Agent(secondFixture.config, { server: base, deviceId: second, token: secondToken }, () => {}); agents.push(secondAgent); secondAgent.start();
  await waitFor(() => relay.hub.devices().filter(device => device.online).length === 2);
  const multi = await makeClient((await mint(['read'], [credential.deviceId, second])).token);
  assert.equal((await multi.callTool({ name: 'list_directory', arguments: { projectId: 'workspace' } })).isError, true);
  assert.ok(!(await multi.callTool({ name: 'list_directory', arguments: { projectId: 'workspace', deviceId: second } })).isError);
  await post(`/api/devices/${credential.deviceId}/rename`, { name: 'Persistent admin name' }, admin);
  await post(`/api/devices/${credential.deviceId}/pause`, {}, admin);
  await waitFor(() => !relay.hub.devices().find(device => device.id === credential.deviceId)?.online);
  assert.equal((await client.callTool({ name: 'list_directory', arguments: { projectId: 'workspace', deviceId: credential.deviceId } })).isError, true);
  await post(`/api/devices/${credential.deviceId}/resume`, {}, admin);
  await waitFor(() => relay.hub.devices().find(device => device.id === credential.deviceId)?.online);
  assert.equal(relay.hub.devices().find(device => device.id === credential.deviceId)?.name, 'Persistent admin name');
  const logs = await (await fetch(base + '/api/audit?limit=1000', { headers: { cookie } })).json() as any[];
  assert.ok(logs.some(row => row.tool === 'write_file' && row.status === 'ok'));
  assert.ok(!JSON.stringify(logs).includes('private-content-marker'));
  await post(`/api/tokens/${pat.tokenId}/revoke`, {}, admin);
  await assert.rejects(client.listTools(), /invalid_token/);
  await post(`/api/devices/${credential.deviceId}/revoke`, {}, admin);
  await waitFor(() => !relay.hub.devices().some(device => device.id === credential.deviceId));
});

test('OAuth DCR + PKCE + consent + resource binding + rotating refresh + replay revocation', async t => {
  const f = await fixture(), port = await freePort(), base = `http://127.0.0.1:${port}`;
  const relay = createHomeServer({ host: '127.0.0.1', port, publicUrl: base, db: path.join(f.directory, 'server.sqlite'), password: 'test-password-strong-123', sessionSecret: 's'.repeat(64), trustProxyHops: 0, retentionDays: 90 });
  await relay.listen(); t.after(async () => { await relay.close(); await f.cleanup(); });
  const metadata = await (await fetch(base + '/.well-known/oauth-authorization-server')).json() as any;
  assert.ok(metadata.code_challenge_methods_supported.includes('S256'));
  const protectedResource = await (await fetch(base + '/.well-known/oauth-protected-resource/mcp')).json() as any;
  assert.equal(protectedResource.resource, base + '/mcp');
  assert.equal((await (await fetch(base + '/.well-known/oauth-protected-resource')).json() as any).resource, base + '/mcp');
  const register = async (redirect: string) => fetch(metadata.registration_endpoint, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ client_name: 'test-oauth', redirect_uris: [redirect], token_endpoint_auth_method: 'none', grant_types: ['authorization_code', 'refresh_token'], response_types: ['code'] }) });
  assert.equal((await register('https://evil.example/callback#bad')).status, 400);
  const registered = await register('http://localhost:9876/callback');
  assert.equal(registered.status, 201);
  const client = await registered.json() as any;
  const verifier = 'a'.repeat(64), challenge = createHash('sha256').update(verifier).digest('base64url');
  const query = new URLSearchParams({ response_type: 'code', client_id: client.client_id, redirect_uri: client.redirect_uris[0], code_challenge: challenge, code_challenge_method: 'S256', resource: base + '/mcp', scope: 'read write', state: 'state123' });
  const authorization = await fetch(`${metadata.authorization_endpoint}?${query}`, { redirect: 'manual' });
  assert.equal(authorization.status, 302);
  const consentPath = authorization.headers.get('location')!;
  const login = await fetch(base + '/login', { method: 'POST', headers: { 'content-type': 'application/json', origin: base }, body: JSON.stringify({ password: 'test-password-strong-123' }), redirect: 'manual' });
  const cookie = login.headers.getSetCookie()[0]!.split(';')[0]!;
  const state = await (await fetch(base + '/api/state', { headers: { cookie } })).json() as any;
  const deviceId = randomUUID();
  relay.store.put('devices', deviceId, { id: deviceId, name: 'device', revoked: false, paused: false, projects: [{ id: 'workspace', name: 'Workspace', readOnly: false, commands: [] }], platform: '', lastSeen: 0, created: Date.now(), tokenHash: 'hash' });
  const consent = await fetch(base + consentPath, { headers: { cookie } }); assert.equal(consent.status, 200);
  const grant = await fetch(base + '/consent', { method: 'POST', headers: { cookie, origin: base, 'content-type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ request: new URL(base + consentPath).searchParams.get('request')!, _csrf: state.csrf, decision: 'allow', scopes: 'read', devices: deviceId, projects: `${deviceId}:workspace` }), redirect: 'manual' });
  assert.equal(grant.status, 302);
  const callback = new URL(grant.headers.get('location')!);
  assert.equal(callback.searchParams.get('state'), 'state123'); assert.equal(callback.searchParams.get('iss'), metadata.issuer);
  const code = callback.searchParams.get('code')!;
  const exchange = (body: Record<string, string>) => fetch(metadata.token_endpoint, { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ client_id: client.client_id, ...body }) });
  assert.equal((await exchange({ grant_type: 'authorization_code', code, redirect_uri: client.redirect_uris[0], code_verifier: 'b'.repeat(64), resource: base + '/mcp' })).status, 400);
  const exchanged = await exchange({ grant_type: 'authorization_code', code, redirect_uri: client.redirect_uris[0], code_verifier: verifier, resource: base + '/mcp' });
  assert.equal(exchanged.status, 200);
  const tokens = await exchanged.json() as any; assert.equal(tokens.scope, 'read');
  assert.deepEqual((await relay.oauth.verifyAccessToken(tokens.access_token)).extra.principal.projectGrants, { [deviceId]: ['workspace'] });
  assert.equal((await exchange({ grant_type: 'authorization_code', code, redirect_uri: client.redirect_uris[0], code_verifier: verifier })).status, 400);
  assert.equal((await exchange({ grant_type: 'refresh_token', refresh_token: tokens.refresh_token, resource: 'https://evil.example/mcp' })).status, 400);
  const refreshed = await exchange({ grant_type: 'refresh_token', refresh_token: tokens.refresh_token, resource: base + '/mcp' });
  assert.equal(refreshed.status, 200);
  const rotated = await refreshed.json() as any;
  assert.deepEqual((await relay.oauth.verifyAccessToken(rotated.access_token)).extra.principal.projectGrants, { [deviceId]: ['workspace'] });
  assert.equal((await exchange({ grant_type: 'refresh_token', refresh_token: tokens.refresh_token, resource: base + '/mcp' })).status, 400);
  await assert.rejects(relay.oauth.verifyAccessToken(rotated.access_token), /Invalid or expired/);
  const dbContents = JSON.stringify(relay.store.all('tokens')) + JSON.stringify(relay.store.all('clients'));
  assert.ok(!dbContents.includes(tokens.access_token)); assert.ok(!dbContents.includes(tokens.refresh_token));
});

test('long jobs remain observable after relay restart with persisted credentials', async t => {
  const f = await fixture(), port = await freePort(), base = `http://127.0.0.1:${port}`;
  const config = { host: '127.0.0.1', port, publicUrl: base, db: path.join(f.directory, 'server.sqlite'), password: 'strong-test-password', sessionSecret: 's'.repeat(64), trustProxyHops: 0, retentionDays: 90 };
  let relay = createHomeServer(config);
  await relay.listen();
  const { hash } = await import('../src/server/store.js');
  const deviceId = randomUUID(), raw = 'd'.repeat(64);
  relay.store.put('devices', deviceId, { id: deviceId, name: 'device', tokenHash: hash(raw), revoked: false, paused: false, projects: [], platform: '', lastSeen: 0, created: Date.now() });
  const token = relay.store.mintToken({ id: 'persistent-owner', scopes: ['read', 'execute'], devices: [deviceId], projects: null, clientId: 'restart-test', family: randomUUID(), expires: Date.now() + 60000, kind: 'pat' });
  f.config.server = base;
  const agent = new Agent(f.config, { server: base, deviceId, token: raw }, () => {}); agent.start();
  const clients: Client[] = [];
  t.after(async () => { for (const client of clients) await client.close(); await agent.close(); await relay.close(); await f.cleanup(); });
  await waitFor(() => relay.hub.devices().some(device => device.online));
  const client = new Client({ name: 'restart-test', version: '1' }); clients.push(client);
  const transport = () => new StreamableHTTPClientTransport(new URL(base + '/mcp'), { requestInit: { headers: { Authorization: `Bearer ${token}` } } });
  await client.connect(transport());
  const started = await client.callTool({ name: 'start_process', arguments: { deviceId, projectId: 'workspace', executable: process.execPath, args: ['-e', 'console.log("before-restart");setTimeout(()=>console.log("after-restart"),2500)'] } }) as any;
  const processId = JSON.parse(started.content[0].text).id;
  await relay.close();
  relay = createHomeServer(config); await relay.listen();
  await waitFor(() => relay.hub.devices().some(device => device.online));
  const reconnected = new Client({ name: 'restart-test', version: '1' }); clients.push(reconnected); await reconnected.connect(transport());
  const done = await waitFor(async () => {
    const response = await reconnected.callTool({ name: 'read_process_output', arguments: { deviceId, projectId: 'workspace', processId } }) as any;
    assert.ok(!response.isError); const value = JSON.parse(response.content[0].text); return value.finished ? value : undefined;
  });
  assert.equal(done.state, 'exited'); assert.ok(done.output.includes('before-restart')); assert.ok(done.output.includes('after-restart'));
});
