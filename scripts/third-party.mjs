import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const lock = JSON.parse(await readFile(path.join(root, 'package-lock.json'), 'utf8'));
const packages = Object.entries(lock.packages)
  .filter(([location, entry]) => location.startsWith('node_modules/') && !entry.dev && !entry.link)
  .sort(([a], [b]) => a.localeCompare(b, 'en'));
const sections = [];
for (const [location, entry] of packages) {
  const directory = path.join(root, location);
  let manifest;
  try { manifest = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8')); }
  catch { throw new Error(`Install the locked dependency tree before generating notices: ${location}`); }
  if (manifest.version !== entry.version) throw new Error(`Installed version differs from lockfile: ${location}`);
  const files = (await readdir(directory))
    .filter(name => /^(licen[cs]e|copying|notice)(?:$|[.-])/i.test(name))
    .sort();
  if (!files.length) throw new Error(`No license/notice file found in ${location}; review its distribution manually`);
  const texts = [];
  for (const name of files) {
    const text = (await readFile(path.join(directory, name), 'utf8')).replace(/\r\n/g, '\n').trim();
    texts.push(`--- ${name} ---\n${text}`);
  }
  sections.push([
    `${manifest.name}@${manifest.version}`,
    `License metadata: ${typeof manifest.license === 'string' ? manifest.license : entry.license ?? 'See supplied license files'}`,
    `Lockfile location: ${location}`,
    ...texts,
  ].join('\n\n'));
}
const text = [
  'HomeAgent — locked npm runtime dependency notices',
  'Generated by scripts/third-party.mjs. Do not edit individual entries.',
  'Original license/notice files are reproduced below. Metadata is informational; supplied terms govern each package.',
  `Production packages: ${packages.length}`,
  ...sections.map(section => `${'='.repeat(80)}\n\n${section}`),
  '',
].join('\n\n');
const target = path.join(root, 'licenses/npm-runtime.txt');
if (process.argv.includes('--check')) {
  const existing = await readFile(target, 'utf8').catch(() => '');
  if (existing.replace(/\r\n/g, '\n') !== text) throw new Error('Dependency notices are missing or stale. Run npm run notices.');
  console.log(`Dependency notices match ${packages.length} locked production packages.`);
} else {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, text);
  console.log(`Generated notices for ${packages.length} locked production packages.`);
}
